const ORDER = ['fr', 'en'];
let current = 'fr';
const listeners = new Set();

export function getLang() {
  return current;
}

export function setLang(lang) {
  if (!STRINGS[lang] || lang === current) return;
  current = lang;
  try { localStorage.setItem('bookish.lang', lang); } catch (_) { /* private mode */ }
  document.documentElement.lang = lang;
  listeners.forEach((fn) => fn(lang));
}

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem('bookish.lang'); } catch (_) { /* ignore */ }
  if (!saved) {
    const nav = (navigator.language || 'fr').slice(0, 2).toLowerCase();
    saved = ORDER.includes(nav) ? nav : 'fr';
  }
  current = STRINGS[saved] ? saved : 'fr';
  document.documentElement.lang = current;
  return current;
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Translate a key, interpolating {placeholders}. */
export function t(key, vars) {
  const dict = STRINGS[current] || STRINGS.fr;
  let s = dict[key] ?? STRINGS.fr[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
  }
  return s;
}

/** All keys defined in the FR dictionary (used by the coverage test). */
export function frKeys() {
  return Object.keys(STRINGS.fr);
}
